#!/usr/bin/env python3
"""
Render the QA handover evidence: what was proved, by which test, from the TRX the test run wrote.

    dotnet test ePACS.Installer.sln -c Release --logger "trx;LogFileName=installer.trx" --results-directory artifacts/test-results
    python3 build/installer-test-evidence.py artifacts/test-results/installer.trx > docs/testing/installer-evidence.md

Generated, not written: the table QA starts from is the table the run produced. Skipped tests are
listed with their reason, so "skipped because no MySQL" is visible as such and never mistaken for
a pass. The refusal matrix is called out separately, because a refusal is a promise to an operator.
"""
import collections
import sys
import xml.etree.ElementTree as ET

NS = {"t": "http://microsoft.com/schemas/VisualStudio/TeamTest/2010"}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    tree = ET.parse(sys.argv[1])
    root = tree.getroot()
    defs = {d.get("id"): d for d in root.iter("{%s}UnitTest" % NS["t"])}
    results = list(root.iter("{%s}UnitTestResult" % NS["t"]))
    by_class = collections.defaultdict(list)
    skipped = []
    for r in results:
        d = defs.get(r.get("testId"))
        method = d.find("t:TestMethod", NS) if d is not None else None
        cls = (method.get("className") if method is not None else "?").split(".")[-1]
        name = r.get("testName").split(".")[-1]
        outcome = r.get("outcome")
        by_class[cls].append((name, outcome))
        if outcome == "NotExecuted":
            msg = r.find("t:Output/t:ErrorInfo/t:Message", NS)
            skipped.append((cls, name, (msg.text or "").strip() if msg is not None else ""))
    counters = root.find("t:ResultSummary/t:Counters", NS)
    total = int(counters.get("total")); passed = int(counters.get("passed")); failed = int(counters.get("failed"))
    print("# Installer test evidence\n")
    print("Generated by build/installer-test-evidence.py from the test run's TRX. **%d tests: %d passed, %d failed, %d skipped.**\n" % (total, passed, failed, len(skipped)))
    if failed:
        print("> **%d FAILED.** This evidence pack is not a handover.\n" % failed)
    print("## The refusal matrix\n")
    print("| Test | Outcome |\n|---|---|")
    for name, outcome in sorted(by_class.get("RefusalMatrixTests", [])):
        print("| %s | %s |" % (name.replace("_", " "), outcome))
    print("\n## By engine\n")
    print("| Engine (test class) | Tests | Passed | Skipped |\n|---|---|---|---|")
    for cls in sorted(by_class):
        rows = by_class[cls]
        print("| %s | %d | %d | %d |" % (cls, len(rows), sum(1 for _, o in rows if o == "Passed"), sum(1 for _, o in rows if o == "NotExecuted")))
    print("\n## Skipped, and why\n")
    if not skipped:
        print("None.")
    for cls, name, why in skipped:
        print("- `%s.%s` — %s" % (cls, name, why or "no reason recorded"))
    print("\n## Every test\n")
    for cls in sorted(by_class):
        print("### %s\n" % cls)
        for name, outcome in sorted(by_class[cls]):
            mark = {"Passed": "✅", "Failed": "❌", "NotExecuted": "⏭"}.get(outcome, "?")
            print("- %s %s" % (mark, name.replace("_", " ")))
        print()
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
